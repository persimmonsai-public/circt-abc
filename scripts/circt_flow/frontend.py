"""Front end: elaborate a design from its manifest and lower it to core MLIR.

    python3 -m circt_flow.frontend <manifest.yaml> <profile.yaml> <out_dir>
        [--src <checkout>]

The manifest (designs/<name>/manifest.yaml) names the RTL source (a git
repository at a pinned commit), the file list, include directories, defines,
parameter overrides and the design's clock-gating primitive; the profile
(profiles/<name>.yaml) names the ICG cell that primitive maps to. Output is
<out_dir>/<top>_core.mlir: hw/comb/seq with `seq.firreg` still present, the
input of the flow's stage 1.

Steps:
  1. The source is fetched at its commit into the cache
     (<cache>/src/<name>-<commit>), unless --src points at a checkout, which
     must be at that commit.
  2. The clock-gating primitive is written as a module instantiating the
     profile's ICG cell, and that cell gets an empty-body declaration with
     its liberty port list.
  3. circt-verilog --ir-llhd elaborates the design. It stops before its own
     LLHD pipeline, whose behaviour drifts with every CIRCT commit; step 5
     is the explicit, pinned copy of it.
  4. The ICG declaration's elaborated body is replaced by an extern
     declaration (externalize_stub_cells.py): circt-verilog has no
     blackbox-module concept and would otherwise drive the output with a
     constant, cutting the clock to everything behind the gate.
  5. circt-opt runs the LLHD lowering to core dialects.
"""
from __future__ import annotations

import argparse
import importlib.util
import os
import subprocess
import sys
from pathlib import Path

import yaml

from . import profile as profile_mod

SCRIPTS = Path(__file__).resolve().parent.parent

# circt-verilog's populateLlhdToCorePipeline, spelled out so that it is the
# pinned CIRCT's passes, in this order, that lower every design.
LLHD_PIPELINE = [
    "--llhd-wrap-procedural-ops", "--llhd-inline-calls", "--symbol-dce",
    "--llhd-mem2reg", "--llhd-hoist-signals", "--llhd-deseq",
    "--llhd-lower-processes", "--cse", "--canonicalize",
    "--llhd-unroll-loops", "--cse", "--canonicalize",
    "--llhd-remove-control-flow", "--cse", "--canonicalize",
    "--llhd-combine-drives", "--llhd-sig2reg", "--llhd-lower-processes",
    "--cse", "--canonicalize", "--map-arith-to-comb",
]


def _load_script(name: str):
    spec = importlib.util.spec_from_file_location(name, SCRIPTS / f"{name}.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def _run(cmd, **kw) -> None:
    print("[frontend] " + " ".join(str(c) for c in cmd[:3]) + " ...")
    subprocess.run([str(c) for c in cmd], check=True, **kw)


def fetch_source(design: dict, src: Path | None) -> Path:
    s = design["source"]
    commit = s["commit"]
    if src is None:
        src = (profile_mod.cache_root() / "src"
               / f"{design['name']}-{commit[:12]}")
        if not (src / ".git").exists():
            src.mkdir(parents=True, exist_ok=True)
            _run(["git", "-C", src, "init", "-q"])
            _run(["git", "-C", src, "fetch", "-q", "--depth", "1",
                  s["git"], commit])
            _run(["git", "-C", src, "checkout", "-q", "FETCH_HEAD"])
    head = subprocess.run(["git", "-C", str(src), "rev-parse", "HEAD"],
                          capture_output=True, text=True,
                          check=True).stdout.strip()
    if head != commit:
        sys.exit(f"frontend: {src} is at {head}, the manifest pins {commit}")
    return src


def clock_gate_files(design: dict, prof: profile_mod.Profile,
                     out_dir: Path) -> list[Path]:
    """The clock-gating primitive mapped onto the profile's ICG cell, and
    an empty-body declaration of that cell with its liberty port list."""
    cg, icg = design["clock_gate"], prof.icg
    p = cg["ports"]
    wrapper = out_dir / f"{cg['module']}_{prof.name}.sv"
    wrapper.write_text(
        f"// Generated by circt_flow/frontend.py: {cg['module']} on the "
        f"{prof.name} profile's ICG.\n"
        f"module {cg['module']} (\n"
        f"  input  {p['clk']},\n  input  {p['en']},\n"
        f"  input  {p['test_en']},\n  output {p['out']}\n);\n"
        f"  {icg['cell']} u_icg (\n"
        f"    .{icg['clk']}({p['clk']}),\n    .{icg['en']}({p['en']}),\n"
        f"    .{icg['test_en']}({p['test_en']}),\n"
        f"    .{icg['out']}({p['out']})\n  );\nendmodule\n")
    stubs = _load_script("gen_liberty_blackbox_stubs")
    for lib in prof.liberties:
        for name, pins in stubs.parse_cells(
                Path(lib).read_text(errors="ignore")):
            if name == icg["cell"]:
                stub = out_dir / f"{icg['cell']}_stub.sv"
                stub.write_text(stubs.sv_stub(name, pins))
                return [wrapper, stub]
    sys.exit(f"frontend: ICG cell {icg['cell']} not in the profile's "
             "liberties")


def run(manifest: Path, prof: profile_mod.Profile, out_dir: Path,
        circt_verilog: Path, circt_opt: Path, src: Path | None = None) -> Path:
    design = yaml.safe_load(manifest.read_text())["design"]
    top = design["top"]
    out_dir.mkdir(parents=True, exist_ok=True)
    root = fetch_source(design, src)

    files: list[Path] = []
    for f in design["files"]:
        if f == "@clock_gate":
            files += clock_gate_files(design, prof, out_dir)
        else:
            files.append(root / f)
    missing = [str(f) for f in files if not f.is_file()]
    if missing:
        sys.exit("frontend: missing source files: " + ", ".join(missing))

    raw = out_dir / f"{top}.mlir"
    cmd = [circt_verilog, "--ir-llhd"]
    for d in design.get("defines", []):
        cmd += ["-D", d]
    cmd += ["--top", top]
    for k, v in (design.get("parameters") or {}).items():
        cmd += ["-G", f"{k}={v}"]
    for i in design.get("include_dirs", []):
        cmd += ["-I", root / i]
    _run(cmd + files + ["-o", raw])

    _run([sys.executable, SCRIPTS / "externalize_stub_cells.py", raw,
          prof.icg["cell"]])

    core = out_dir / f"{top}_core.mlir"
    _run([circt_opt, raw, *LLHD_PIPELINE, "-o", core])
    print(f"[frontend] core MLIR -> {core}")
    return core


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("manifest", type=Path)
    ap.add_argument("profile", type=Path)
    ap.add_argument("out_dir", type=Path)
    ap.add_argument("--src", type=Path,
                    help="existing checkout of the manifest's source commit")
    bin_dir = SCRIPTS.parent / "third_party" / "circt" / "build" / "bin"
    ap.add_argument("--circt-verilog", type=Path, default=Path(
        os.environ.get("CIRCT_VERILOG", bin_dir / "circt-verilog")))
    ap.add_argument("--circt-opt", type=Path, default=Path(
        os.environ.get("CIRCT_OPT", bin_dir / "circt-opt")))
    a = ap.parse_args(argv)
    run(a.manifest, profile_mod.load(a.profile), a.out_dir,
        a.circt_verilog, a.circt_opt, a.src)
    return 0


if __name__ == "__main__":
    sys.exit(main())
